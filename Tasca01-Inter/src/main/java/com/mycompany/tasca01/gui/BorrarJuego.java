    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        Joc u = (Joc) jComboBox1.getSelectedItem();
        
        for (Lloguer l : GestionDatos.lloguers) {

            if (l.getJoc() == u && !l.isRetornat()) {
                showMessageDialog(this, "El juego tiene un alquiler activo y no se puede borrar");
                return;
            }
        }

        GestionDatos.jocs.remove(u);
        showMessageDialog(this,"Juego borrado");

        dispose();
    }//GEN-LAST:event_jButton1ActionPerformed

