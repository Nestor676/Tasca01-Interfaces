    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        String nombre = txtNombre1.getText().trim();
        String genero = cmbGenero.toString();
        ArrayList<Plataforma> plataformas = new ArrayList<>();

        if (ckPC.isSelected() && (int) uniPC.getValue() != 0) {
            Plataforma p1 = new Plataforma(ckPC.getText(), (int) uniPC.getValue());
            plataformas.add(p1);
        }

        if (ckPS5.isSelected() && (int) uniPS5.getValue() != 0) {
            Plataforma p2 = new Plataforma(ckPS5.getText(), (int) uniPS5.getValue());
            plataformas.add(p2);
        }

        if (ckXbox.isSelected() && (int) uniXbox.getValue() != 0) {
            Plataforma p3 = new Plataforma(ckXbox.getText(), (int) uniXbox.getValue());
            plataformas.add(p3);
        }

        if (ckSwitch.isSelected() && (int) uniSwitch.getValue() != 0) {
            Plataforma p4 = new Plataforma(ckSwitch.getText(), (int) uniSwitch.getValue());
            plataformas.add(p4);
        }

        if (ckPC.isSelected() && (int) uniPC.getValue() <= 0) {
            showMessageDialog(this, "La plataforma PC debe tener al menos una unidad");
            return;
        }

        if (ckPS5.isSelected() && (int) uniPS5.getValue() <= 0) {
            showMessageDialog(this, "La plataforma PS5 debe tener al menos una unidad");
            return;
        }

        if (ckXbox.isSelected() && (int) uniXbox.getValue() <= 0) {
            showMessageDialog(this, "La plataforma Xbox debe tener al menos una unidad");
            return;
        }

        if (ckSwitch.isSelected() && (int) uniSwitch.getValue() <= 0) {
            showMessageDialog(this, "La plataforma Switch debe tener al menos una unidad");
            return;
        }

        Joc j = new Joc(nombre, genero, plataformas);

        if (nombre == null || nombre.trim().equals("")) {
            showMessageDialog(this, "El juego debe de tener nombre");
        } else if (plataformas.isEmpty()) {
            showMessageDialog(this, "El juego debe de tener al menos una plataforma");
        } else {
            GestionDatos.jocs.add(j);

            showMessageDialog(this, "Juego credo correctamente");

            dispose();
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed

