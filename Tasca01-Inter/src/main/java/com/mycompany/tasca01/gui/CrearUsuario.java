    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed

        String nom = txtNom.getText().trim();
        String cognom1 = txtCognom1.getText().trim();
        String cognom2 = txtCognom2.getText().trim();
        String dni = txtDNI.getText().trim();
        String telefon = txtTelefon.getText().trim();

        if (nom.isEmpty() || cognom1.isEmpty() || cognom2.isEmpty() || dni.isEmpty() || telefon.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(this,"Cal omplir tots els camps.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);

            return;
        }

        Usuari nouUsuari = new Usuari(nom, cognom1, cognom2, dni, telefon, new java.util.Date());

        GestionDatos.usuaris.add(nouUsuari);

        javax.swing.JOptionPane.showMessageDialog(this, "Usuari creat correctament.");

        dispose();
    }//GEN-LAST:event_btnConfirmarActionPerformed

