    private void InitializeTable() {

        DefaultTableModel dtm = new DefaultTableModel() {

            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        dtm.setColumnIdentifiers(new String[]{
            "Núm. registre",
            "Título del juego",
            "Usuario",
            "Plataforma",
            "Fecha de inicio",});

        jTable1.setModel(dtm);

        jTable1.getTableHeader().setDefaultRenderer(new MiHeaderRenderer());
    }

    private void cargarTabla() {
        DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();

        dtm.setRowCount(0);

        for (Lloguer l : GestionDatos.lloguers) {
            if (!l.isRetornat()) {
                dtm.addRow(new Object[]{
                    l.getNumeroRegistro(),
                    l.getJoc().getNom(),
                    l.getUsuari().getNom(),
                    l.getPlataforma().getNom(),
                    l.getInicio(),});
            }
        }
    }

    private void mostrarDatosSeleccionados() {

        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            return;
        }

        int numeroRegistro = (int) jTable1.getValueAt(fila, 0);

        for (Lloguer l : GestionDatos.lloguers) {

            if (l.getNumeroRegistro() == numeroRegistro && !l.isRetornat()) {

                txtNombre.setText(l.getJoc().getNom());

                txtUsuario.setText(l.getUsuari().getNom());

                txtPlataforma.setText(l.getPlataforma().getNom());

                txtFecha.setText(l.getInicio().toString());

                break;
            }
        }
    }

    private void limpiarDatos() {

        txtNombre.setText(" ");
        txtUsuario.setText(" ");
        txtPlataforma.setText(" ");
        txtFecha.setText(" ");

    }

