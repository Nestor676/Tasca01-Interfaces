    private void buttonDevolverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonDevolverActionPerformed
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            showMessageDialog(this, "Seleccione un alquiler primero.");
            return;
        }

        int numeroRegistro = (int) jTable1.getValueAt(fila, 0);

        for (Lloguer l : GestionDatos.lloguers) {

            if (l.getNumeroRegistro() == numeroRegistro) {

                l.setRetornat(true);

                showMessageDialog(this, "Alquiler marcado como devuelto correctamente.");

                break;
            }
        }

        cargarTabla();

        limpiarDatos();
    }//GEN-LAST:event_buttonDevolverActionPerformed

